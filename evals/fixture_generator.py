"""A test double that writes Flutter the way a model plausibly would.

Every grading check in this repo — conformance, smoke-test generation, ownership
routing — was developed against `TemplateGenerator`. They are *claimed* to be
naming-agnostic, discovering structure by scanning the output rather than
predicting it from the PRD. That claim has never been tested, because there has
only ever been one generator.

If the harness silently only works on our own templates, the first paid run
returns meaningless numbers and the model gets the blame. So this fixture emits
correct, idiomatic Flutter that satisfies the same PRD while disagreeing with
`TemplateGenerator` on every convention it legitimately could:

    TemplateGenerator                 FixtureGenerator
    lib/ui/observations_screen.dart   lib/ui/observations_page.dart
    class ObservationsScreen          class ObservationsView
    observationListProvider           observationsStreamProvider
    StreamProvider<List<T>>           StreamProvider.autoDispose<List<T>>
    StateNotifierProvider             AsyncNotifierProvider
    routes: {'/observations': ...}    onGenerateRoute with route constants

It is a *correct* app. Anything the harness reports against it is a harness bug,
not a generation bug — which is exactly the signal we need before spending money.
"""

