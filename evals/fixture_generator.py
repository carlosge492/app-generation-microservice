_REPOSITORY = """import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

class Observation {
  const Observation({
    required this.id,
    required this.title,
    required this.notes,
    required this.count,
    required this.verified,
    required this.recordedAt,
  });

  final String id;
  final String title;
  final String notes;
  final num count;
  final bool verified;
  final DateTime recordedAt;

  factory Observation.fromDoc(DocumentSnapshot<Map<String, dynamic>> doc) {
    final data = doc.data() ?? const <String, dynamic>{};
    return Observation(
      id: doc.id,
      title: (data['title'] as String?) ?? '',
      notes: (data['notes'] as String?) ?? '',
      count: (data['count'] as num?) ?? 0,
      verified: (data['verified'] as bool?) ?? false,
      recordedAt: DateTime.tryParse('${data['recordedAt']}') ?? DateTime(1970),
    );
  }

  Map<String, dynamic> toJson() => <String, dynamic>{
        'title': title,
        'notes': notes,
        'count': count,
        'verified': verified,
        'recordedAt': recordedAt.toIso8601String(),
      };
}

final observationsCollection =
    Provider<CollectionReference<Map<String, dynamic>>>((ref) {
  return FirebaseFirestore.instance.collection('observations');
});

final observationsStreamProvider =
    StreamProvider.autoDispose<List<Observation>>((ref) {
  return ref
      .watch(observationsCollection)
      .snapshots()
      .map((snap) => snap.docs.map(Observation.fromDoc).toList());
});

final observationsControllerProvider =
    AsyncNotifierProvider<ObservationsController, void>(
  ObservationsController.new,
);

class ObservationsController extends AsyncNotifier<void> {
  @override
  Future<void> build() async {}

  Future<void> save(Map<String, dynamic> draft) async {
    state = const AsyncValue.loading();
    state = await AsyncValue.guard(() async {
      await ref.read(observationsCollection).add(draft);
    });
  }
}
"""

