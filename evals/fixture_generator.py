class FixtureGenerator(TemplateGenerator):
    """Correct Flutter, none of TemplateGenerator's naming conventions.

    Only valid for the Field Notes PRD (`examples/todo_app.prd.json`); it falls
    back to the template output for anything else so the eval harness stays
    runnable end to end.
    """

    def _is_field_notes(self, prd: PRD) -> bool:
        return prd.package_name == "com.example.fieldnotes"

    def plan(self, prd: PRD) -> Plan:
        if not self._is_field_notes(prd):
            return super().plan(prd)
        return Plan(
            design_md=f"# DESIGN.md — {prd.app_name}\n\nFixture plan.\n",
            pubspec=_PUBSPEC,
            analysis_options=ANALYSIS_OPTIONS,
        )

    def build_ui(self, prd: PRD, design_md: str, diagnostics=None) -> dict[str, str]:
        if not self._is_field_notes(prd):
            return super().build_ui(prd, design_md, diagnostics)
        return {
            "lib/ui/app.dart": _APP,
            "lib/ui/observations_page.dart": _OBSERVATIONS,
            "lib/ui/capture_page.dart": _CAPTURE,
            "lib/ui/settings_page.dart": _SETTINGS,
        }

    def wire_logic(
        self, prd: PRD, design_md: str, ui_files, diagnostics: list[Diagnostic]
    ) -> dict[str, str]:
        if not self._is_field_notes(prd):
            return super().wire_logic(prd, design_md, ui_files, diagnostics)
        return {
            "lib/providers/observations_repository.dart": _REPOSITORY,
            "lib/main.dart": _MAIN,
        }
